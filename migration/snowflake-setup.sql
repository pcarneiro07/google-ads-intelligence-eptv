-- Run with a provisioning role, not with the runtime role.
CREATE ROLE IF NOT EXISTS EPTV_ADS_APP_OWNER;
CREATE ROLE IF NOT EXISTS EPTV_ADS_APP_VIEWER;
CREATE DATABASE IF NOT EXISTS EPTV_APPS;
CREATE SCHEMA IF NOT EXISTS EPTV_APPS.ADS_REVIEW;
CREATE SCHEMA IF NOT EXISTS EPTV_APPS.ADS_BUILDS;
CREATE SCHEMA IF NOT EXISTS EPTV_APPS.ADS_SECRETS;

-- An administrator must provision the generic-string secret OUTSIDE this repository.
-- Object: EPTV_APPS.ADS_SECRETS.GOOGLE_ADS_SERVICE_ACCOUNT
-- Type: GENERIC_STRING. Value: service-account JSON supplied by the approved vault.
-- Never paste the actual key in this SQL file, GitHub variables, build args or logs.

CREATE NETWORK RULE IF NOT EXISTS EPTV_APPS.ADS_SECRETS.GOOGLE_ADS_EGRESS
  MODE = EGRESS TYPE = HOST_PORT
  VALUE_LIST = ('oauth2.googleapis.com:443', 'googleads.googleapis.com:443');

-- Requires the Secret above to have been created by the administrator.
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS EPTV_GOOGLE_ADS_EAI
  ALLOWED_NETWORK_RULES = (EPTV_APPS.ADS_SECRETS.GOOGLE_ADS_EGRESS)
  ALLOWED_AUTHENTICATION_SECRETS = (EPTV_APPS.ADS_SECRETS.GOOGLE_ADS_SERVICE_ACCOUNT)
  ENABLED = TRUE;

GRANT USAGE ON DATABASE EPTV_APPS TO ROLE EPTV_ADS_APP_OWNER;
GRANT USAGE ON SCHEMA EPTV_APPS.ADS_REVIEW TO ROLE EPTV_ADS_APP_OWNER;
GRANT USAGE ON SCHEMA EPTV_APPS.ADS_BUILDS TO ROLE EPTV_ADS_APP_OWNER;
GRANT USAGE ON SCHEMA EPTV_APPS.ADS_SECRETS TO ROLE EPTV_ADS_APP_OWNER;
GRANT READ ON SECRET EPTV_APPS.ADS_SECRETS.GOOGLE_ADS_SERVICE_ACCOUNT TO ROLE EPTV_ADS_APP_OWNER;
GRANT USAGE ON INTEGRATION EPTV_GOOGLE_ADS_EAI TO ROLE EPTV_ADS_APP_OWNER;
GRANT CREATE APPLICATION SERVICE ON SCHEMA EPTV_APPS.ADS_REVIEW TO ROLE EPTV_ADS_APP_OWNER;
GRANT CREATE ARTIFACT REPOSITORY ON SCHEMA EPTV_APPS.ADS_REVIEW TO ROLE EPTV_ADS_APP_OWNER;
GRANT CREATE STAGE ON SCHEMA EPTV_APPS.ADS_REVIEW TO ROLE EPTV_ADS_APP_OWNER;
GRANT CREATE SERVICE ON SCHEMA EPTV_APPS.ADS_BUILDS TO ROLE EPTV_ADS_APP_OWNER;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE EPTV_ADS_APP_OWNER;
-- Existing warehouse must be approved/provisioned independently; no new size guessed.
GRANT USAGE ON WAREHOUSE EPTV_APPS_QUERY_WH TO ROLE EPTV_ADS_APP_OWNER;

